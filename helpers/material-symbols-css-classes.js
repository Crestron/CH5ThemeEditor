const fs = require('fs');
const logging = require('./logging');
const fse = require('fs-extra');

const materialSymbolsTypesPath = `./node_modules/material-symbols/index.d.ts`;
const families = ["outlined", "rounded", "sharp"];
const defaultOutputPath = './generated-metadata/material-symbols-icons.css';

// Material Symbols ships icon names in its TypeScript definition rather than a JSON file.
const extractMaterialSymbolNames = (dTsContent) => {
  const tupleMatch = dTsContent.match(/type MaterialSymbols = \[([\s\S]*?)\];/);
  if (!tupleMatch) {
    throw new Error('Unable to parse Material Symbols names from type definition.');
  }
  const uniqueNames = new Set();
  const nameMatches = tupleMatch[1].matchAll(/"([^"]+)"/g);
  for (const match of nameMatches) {
    uniqueNames.add(match[1]);
  }
  return Array.from(uniqueNames);
};

// Material Symbols names use only [a-z0-9_]. Class attributes accept names that start with a
// digit (e.g. "123", "10k"), but a CSS selector must escape a leading digit as "\3X " so the
// rule still matches class="123".
const escapeClassSelector = (name) => {
  if (/^[0-9]/.test(name)) {
    return '\\3' + name[0] + ' ' + name.slice(1);
  }
  return name;
};

// Generates a CSS file with per-icon helper classes for Material Symbols and returns the path it
// was written to. Material Symbols is a ligature font with no per-icon codepoints; the icon name
// itself is the ligature. These helper rules let an icon be rendered with class names instead of
// text content, e.g. <i class="material-symbols-outlined home"></i>. Rules are scoped to the family
// class so a bare icon class (like "home") does not inject content into unrelated elements.
const generateMaterialSymbolsCss = (outputPath = defaultOutputPath) => {
  logging.loading('Material Symbols CSS classes');

  const typeDef = fs.readFileSync(materialSymbolsTypesPath, 'utf8');
  const names = extractMaterialSymbolNames(typeDef);

  const responseArray = [];
  responseArray.push(
    '/* Auto-generated by helpers/material-symbols-css-classes.js. Do not edit by hand. */'
  );

  for (const family of families) {
    const familyClass = `.material-symbols-${family}`;
    for (const name of names) {
      const selector = `${familyClass}.${escapeClassSelector(name)}::before`;
      responseArray.push(`${selector} { content: "${name}"; }`);
    }
  }

  fse.outputFileSync(outputPath, responseArray.join("\n") + "\n");

  logging.success(`Material Symbols CSS classes written to ${outputPath} (${names.length} icons x ${families.length} families).`);
  return outputPath;
};

// Allow running directly via `node helpers/material-symbols-css-classes.js [--writeTo <path>]`.
if (require.main === module) {
  try {
    generateMaterialSymbolsCss(process.argv[3] !== undefined ? process.argv[3] : defaultOutputPath);
  } catch (err) {
    logging.error(err.message || err);
    console.error(err);
    process.exitCode = 1;
  }
}

module.exports = { generateMaterialSymbolsCss };
